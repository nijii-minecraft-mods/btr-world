package dev.aliska.bocchi;

/**
 * Оригинальные нотные фразы для репетиций героинь у инструментов.
 * Не содержит аудиозаписей или прямых транскрипций саундтрека из аниме.
 */
public final class OriginalMusic {
    private OriginalMusic() {}

    private static final int[][] PHRASES = {
        // Боччи (соло-гитара)
        {12, 16, 19, 16, 14, 17, 21, 17, 12, 19, 16, 14, 9, 12, 16, 12, 14, 17, 19, 21, 19, 17, 14, 12, 9, 12, 14, 16, 14, 12, 9, 12},
        // Нидзика (барабаны / колокольчики)
        {12, 12, 19, 16, 12, 14, 17, 14, 16, 16, 21, 19, 17, 14, 12, 12, 19, 16, 14, 12, 14, 17, 19, 17, 16, 14, 12, 9, 12, 16, 14, 12},
        // Рё (бас)
        {0, 7, 3, 7, 5, 12, 8, 12, 3, 10, 7, 10, 0, 7, 5, 3, 8, 3, 0, 3, 5, 0, 8, 5, 3, 10, 5, 7, 0, 3, 7, 0},
        // Кита (флейта / вокал)
        {16, 19, 21, 19, 17, 16, 14, 12, 14, 17, 21, 19, 16, 14, 12, 16, 19, 21, 24, 21, 19, 17, 16, 14, 17, 19, 16, 14, 12, 14, 16, 12},
        // Сейка (ударные / ритм лайвхауса)
        {14, 14, 17, 14, 12, 14, 16, 14, 17, 19, 17, 14, 12, 10, 12, 14, 16, 17, 19, 21, 19, 17, 16, 14, 12, 14, 16, 17, 16, 14, 12, 14},
        // Кикури (бас-соло SICK HACK)
        {2, 5, 7, 5, 2, 8, 7, 2, 5, 8, 10, 8, 5, 7, 5, 2, 0, 3, 7, 5, 2, 5, 8, 10, 12, 10, 7, 5, 2, 5, 7, 2},
        // ПА-сан (электронный бит / звукорежиссура)
        {12, 15, 12, 17, 15, 12, 10, 12, 15, 17, 19, 17, 15, 12, 15, 17, 20, 19, 17, 15, 12, 10, 12, 15, 17, 15, 12, 10, 8, 10, 12, 12}
    };

    /**
     * Вычисляет высоту ноты (0..24 в диапазоне ванильного нотного блока)
     * для заданной героини и номера доли мелодии.
     * Чередует куплет, ответ, нижний регистр и припев без коротких петель.
     */
    public static int note(int heroine, int beat) {
        int[] phrase = PHRASES[Math.floorMod(heroine, PHRASES.length)];
        int section = Math.floorDiv(beat, phrase.length);
        int note = phrase[Math.floorMod(beat, phrase.length)];

        // Чередование секций фразы для создания живой развивающейся мелодии
        if (section % 4 == 1) {
            note = phrase[(Math.floorMod(beat, phrase.length) + 8) % phrase.length];
        } else if (section % 4 == 2) {
            note = Math.max(0, note - 5);
        }

        return Math.min(24, note);
    }
}
